"""
=============================================================
  DATA AUGMENTATION — Match22 Dataset
  Team: Light Seekers | Course: CSE-4889
  Expanding Match22 dataset from ~1,600 to ~20,000 rows
  Methods:
    1. Gaussian Noise Injection (numeric features)
    2. KNN Feature Interpolation (SMOTE-style neighborhood sampling)
    3. Crop & Season Aware Yield Scaling
=============================================================
"""

import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import os
import sys
import warnings
warnings.filterwarnings('ignore')
from sklearn.neighbors import NearestNeighbors

# Enable UTF-8 encoding for Windows console output
sys.stdout.reconfigure(encoding='utf-8')

np.random.seed(42)

INPUT_FILE = 'Data/Match22-data/Data/merged_dataset.csv'
OUTPUT_FILE = 'Data/Match22-data/Data/augmented_dataset.csv'
SUMMARY_IMG = 'Data/Match22-data/Output/augmentation_summary.png'

os.makedirs('Data/Match22-data/Output', exist_ok=True)

# ─────────────────────────────────────────────
# STEP 1: Load Merged Match22 Dataset
# ─────────────────────────────────────────────
print("=" * 60)
print("STEP 1: Loading Data/Match22-data/Data/merged_dataset.csv")
print("=" * 60)

df = pd.read_csv(INPUT_FILE)
print(f"  Original shape : {df.shape}")

df['_orig_id'] = np.arange(len(df))

CAT_COLS = ['District', 'Season', 'Crop Name', 'Transplant', 'Growth', 'Harvest', 'Crop_Label_22']
NUM_COLS = ['Area', 'N', 'P', 'K', 'ph',
            'Avg Temp', 'Min Temp', 'Max Temp',
            'Avg Humidity', 'Min Relative Humidity', 'Max Relative Humidity',
            'Rainfall', 'AP Ratio', 'Production']

CAT_COLS = [c for c in CAT_COLS if c in df.columns]
NUM_COLS = [c for c in NUM_COLS if c in df.columns]

# Per-column noise scale
NOISE_SCALE = {
    'Area': 0.10, 'N': 0.08, 'P': 0.08, 'K': 0.08, 'ph': 0.03,
    'Avg Temp': 0.05, 'Min Temp': 0.05, 'Max Temp': 0.05,
    'Avg Humidity': 0.05, 'Min Relative Humidity': 0.05, 'Max Relative Humidity': 0.05,
    'Rainfall': 0.08, 'AP Ratio': 0.05, 'Production': 0.12
}

col_stats = {}
for col in NUM_COLS:
    col_stats[col] = {
        'min': df[col].min(),
        'max': df[col].max(),
        'std': df[col].std(),
        'mean': df[col].mean()
    }

all_augmented = [df.copy()]

# ─────────────────────────────────────────────
# STEP 2: Method A — Gaussian Noise Injection (x5 copies)
# ─────────────────────────────────────────────
print("\n" + "=" * 60)
print("STEP 2: Method A — Gaussian Noise Injection (x5 copies)")
print("=" * 60)

def add_noise(source_df, n_copies=5):
    noise_rows = []
    for _ in range(n_copies):
        copy_df = source_df.copy()
        for col in NUM_COLS:
            scale = NOISE_SCALE.get(col, 0.05)
            std_val = col_stats[col]['std']
            noise = np.random.normal(0, std_val * scale, size=len(copy_df))
            copy_df[col] = copy_df[col] + noise
            # Clip bounds
            min_val = max(0, col_stats[col]['min'] * 0.7) if col in ['Area', 'Production', 'Rainfall', 'N', 'P', 'K'] else col_stats[col]['min'] * 0.8
            max_val = col_stats[col]['max'] * 1.2
            copy_df[col] = np.clip(copy_df[col], min_val, max_val)
        noise_rows.append(copy_df)
    return pd.concat(noise_rows, ignore_index=True)

df_noise = add_noise(df, n_copies=5)
all_augmented.append(df_noise)
print(f"  Generated by Noise Injection : {len(df_noise)} rows")

# ─────────────────────────────────────────────
# STEP 3: Method B — KNN Interpolation (x3 copies)
# ─────────────────────────────────────────────
print("\n" + "=" * 60)
print("STEP 3: Method B — KNN Interpolation (x3 copies)")
print("=" * 60)

def knn_interpolate(source_df, n_copies=3, k_neighbors=5):
    interpolated_list = []
    crops = source_df['Crop Name'].unique()
    
    for crop in crops:
        crop_df = source_df[source_df['Crop Name'] == crop].copy()
        if len(crop_df) < k_neighbors:
            continue
        
        num_matrix = crop_df[NUM_COLS].values
        nbrs = NearestNeighbors(n_neighbors=k_neighbors, algorithm='auto').fit(num_matrix)
        distances, indices = nbrs.kneighbors(num_matrix)
        
        for _ in range(n_copies):
            synth_matrix = np.zeros_like(num_matrix)
            for i in range(len(crop_df)):
                # Choose random neighbor
                nn_idx = np.random.choice(indices[i, 1:])
                alpha = np.random.uniform(0.1, 0.9)
                synth_matrix[i] = num_matrix[i] + alpha * (num_matrix[nn_idx] - num_matrix[i])
            
            synth_df = crop_df.copy()
            for idx, col in enumerate(NUM_COLS):
                synth_df[col] = synth_matrix[:, idx]
            interpolated_list.append(synth_df)
            
    if interpolated_list:
        return pd.concat(interpolated_list, ignore_index=True)
    return pd.DataFrame()

df_knn = knn_interpolate(df, n_copies=3, k_neighbors=5)
if len(df_knn) > 0:
    all_augmented.append(df_knn)
    print(f"  Generated by KNN Interpolation: {len(df_knn)} rows")

# ─────────────────────────────────────────────
# STEP 4: Method C — Crop & Season Aware Yield Scaling (x3 copies)
# ─────────────────────────────────────────────
print("\n" + "=" * 60)
print("STEP 4: Method C — Crop & Season Aware Scaling (x3 copies)")
print("=" * 60)

def season_scale(source_df, n_copies=3):
    scaled_list = []
    for _ in range(n_copies):
        copy_df = source_df.copy()
        # Realistic climate & area perturbation factor (+/- 8%)
        scale_factor = np.random.uniform(0.92, 1.08, size=len(copy_df))
        for col in ['Area', 'Rainfall', 'Production']:
            if col in copy_df.columns:
                copy_df[col] = copy_df[col] * scale_factor
        scaled_list.append(copy_df)
    return pd.concat(scaled_list, ignore_index=True)

df_scale = season_scale(df, n_copies=3)
all_augmented.append(df_scale)
print(f"  Generated by Season Scaling  : {len(df_scale)} rows")

# ─────────────────────────────────────────────
# STEP 5: Combine & Save Augmented Dataset
# ─────────────────────────────────────────────
print("\n" + "=" * 60)
print("STEP 5: Combining & Saving Augmented Dataset")
print("=" * 60)

df_aug = pd.concat(all_augmented, ignore_index=True)
df_aug.to_csv(OUTPUT_FILE, index=False)

print(f"  Original dataset rows : {len(df)}")
print(f"  Augmented dataset rows: {len(df_aug)}")
print(f"  Expansion factor       : {len(df_aug) / len(df):.1f}x growth")
print(f"  Saved to              : {OUTPUT_FILE}")

# ─────────────────────────────────────────────
# STEP 6: Visualization Chart
# ─────────────────────────────────────────────
fig, axes = plt.subplots(1, 2, figsize=(14, 5))
fig.suptitle('Match22 Data Augmentation Summary — Light Seekers | CSE-4889', fontsize=13, fontweight='bold')

# Bar chart of dataset size growth
labels = ['Original', 'Noise (A)', 'KNN (B)', 'Scaling (C)', 'Total Augmented']
counts = [len(df), len(df_noise), len(df_knn), len(df_scale), len(df_aug)]
colors = ['#34495e', '#2ecc71', '#3498db', '#9b59b6', '#e74c3c']

bars = axes[0].bar(labels, counts, color=colors, edgecolor='white', linewidth=1.2)
for b, v in zip(bars, counts):
    axes[0].text(b.get_x() + b.get_width()/2, v + 200, f'{v:,}', ha='center', fontweight='bold', fontsize=10)

axes[0].set_title('Dataset Size Growth Breakdown', fontweight='bold')
axes[0].set_ylabel('Row Count')
axes[0].grid(axis='y', alpha=0.3)

# Production Distribution comparison
axes[1].hist(np.log1p(df['Production']), bins=30, alpha=0.6, color='#34495e', label='Original Data', density=True)
axes[1].hist(np.log1p(df_aug['Production']), bins=30, alpha=0.5, color='#2ecc71', label='Augmented Data', density=True)
axes[1].set_title('Production_log Distribution (Preserved Density)', fontweight='bold')
axes[1].set_xlabel('log(1 + Production)'); axes[1].set_ylabel('Density')
axes[1].legend()
axes[1].grid(alpha=0.3)

plt.tight_layout()
plt.savefig(SUMMARY_IMG, dpi=150, bbox_inches='tight')
plt.close()

print(f"  Saved summary chart to {SUMMARY_IMG}")
print("\n" + "=" * 60)
print("DATA AUGMENTATION COMPLETE ✅")
print("=" * 60)
